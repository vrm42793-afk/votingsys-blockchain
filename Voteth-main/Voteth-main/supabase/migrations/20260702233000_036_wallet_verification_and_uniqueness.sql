-- Description: Enforces wallet uniqueness per user profile, adds challenge nonce column,
-- and provides server-side functions for signature-based wallet linking.

-- 1. Add wallet_nonce column to public.user_profiles
ALTER TABLE public.user_profiles
ADD COLUMN IF NOT EXISTS wallet_nonce TEXT;

-- 2. Enforce wallet address uniqueness: no two users may link the same wallet address
CREATE UNIQUE INDEX IF NOT EXISTS uq_user_profiles_wallet_address 
ON public.user_profiles (LOWER(wallet_address)) 
WHERE wallet_address IS NOT NULL;

-- 3. Function to generate a secure challenge nonce for the authenticated user
CREATE OR REPLACE FUNCTION public.generate_wallet_nonce()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
    v_nonce TEXT;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Authentication required to generate wallet verification challenge';
    END IF;

    -- Cryptographically secure server-generated challenge nonce
    v_nonce := 'voteth-auth-' || encode(gen_random_bytes(16), 'hex') || '-' || EXTRACT(EPOCH FROM NOW())::BIGINT;

    UPDATE public.user_profiles
    SET wallet_nonce = v_nonce
    WHERE id = auth.uid();

    RETURN v_nonce;
END;
$$;

-- 4. Function to link wallet after verification
CREATE OR REPLACE FUNCTION public.link_verified_wallet(
    p_wallet_address TEXT,
    p_expected_nonce TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
    v_current_nonce TEXT;
    v_clean_address TEXT;
    v_existing_user_id UUID;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Authentication required to link wallet';
    END IF;

    v_clean_address := LOWER(TRIM(p_wallet_address));

    -- Validate Ethereum address format (0x + 40 hex chars)
    IF v_clean_address !~ '^0x[0-9a-f]{40}$' THEN
        RAISE EXCEPTION 'Invalid Ethereum address format';
    END IF;

    -- Verify the challenge nonce matches what was generated by the server
    SELECT wallet_nonce INTO v_current_nonce
    FROM public.user_profiles
    WHERE id = auth.uid();

    IF v_current_nonce IS NULL OR v_current_nonce <> p_expected_nonce THEN
        RAISE EXCEPTION 'Invalid or expired wallet verification nonce. Please request a fresh challenge.';
    END IF;

    -- Prevent linking if another account already has this wallet
    SELECT id INTO v_existing_user_id
    FROM public.user_profiles
    WHERE LOWER(wallet_address) = v_clean_address
      AND id <> auth.uid();

    IF v_existing_user_id IS NOT NULL THEN
        RAISE EXCEPTION 'This wallet address is already linked to another VotEth account.';
    END IF;

    -- Atomically update the wallet address and invalidate the nonce
    UPDATE public.user_profiles
    SET wallet_address = v_clean_address,
        wallet_nonce = NULL
    WHERE id = auth.uid();

    RETURN jsonb_build_object(
        'success', true,
        'wallet_address', v_clean_address,
        'user_id', auth.uid()
    );
END;
$$;
